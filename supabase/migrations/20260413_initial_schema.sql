create extension if not exists pgcrypto;

create table if not exists public.stores (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  short_description text,
  seo_title text,
  seo_description text,
  suburb text,
  state text,
  address_line_1 text,
  address_line_2 text,
  postcode text,
  phone text,
  email text,
  opening_hours text,
  hero_heading text,
  hero_text text,
  is_active boolean not null default true,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  description text,
  sort_order integer not null default 0,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.suppliers (
  id bigint generated by default as identity primary key,
  name text not null,
  contact_name text,
  email text,
  phone text,
  website_url text,
  notes text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sku text not null unique,
  slug text not null unique,
  name text not null,
  brand text,
  model text,
  category_id bigint references public.categories(id),
  supplier_id bigint references public.suppliers(id),
  short_description text,
  description text,
  condition_label text,
  compatibility text,
  cost_price numeric(10,2),
  wholesale_price numeric(10,2),
  retail_price numeric(10,2),
  compare_at_price numeric(10,2),
  image_url text,
  supplier_image_url text,
  supplier_product_url text,
  stock_quantity integer not null default 0,
  min_order_quantity integer not null default 1,
  is_featured boolean not null default false,
  is_visible boolean not null default true,
  seo_title text,
  seo_description text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.product_images (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  image_url text not null,
  alt_text text,
  sort_order integer not null default 0,
  created_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.product_store_inventory (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  store_id bigint not null references public.stores(id) on delete cascade,
  quantity integer not null default 0,
  shelf_location text,
  updated_at timestamptz not null default timezone('utc', now()),
  unique (product_id, store_id)
);

create table if not exists public.price_history (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  source_name text,
  source_url text,
  old_cost_price numeric(10,2),
  new_cost_price numeric(10,2),
  old_wholesale_price numeric(10,2),
  new_wholesale_price numeric(10,2),
  old_retail_price numeric(10,2),
  new_retail_price numeric(10,2),
  changed_at timestamptz not null default timezone('utc', now())
);

create table if not exists public.repair_bookings (
  id bigint generated by default as identity primary key,
  booking_code text not null unique,
  store_slug text not null,
  repair_category text not null check (repair_category in ('phone', 'computer', 'tablet', 'gaming_console')),
  brand text,
  device_model text not null,
  issue_description text not null,
  preferred_date date,
  preferred_time text,
  customer_name text not null,
  phone text not null,
  email text not null,
  preferred_contact_method text not null default 'phone' check (preferred_contact_method in ('phone', 'email', 'sms')),
  status text not null default 'new' check (status in ('new', 'contacted', 'in_progress', 'completed', 'cancelled')),
  admin_notes text,
  ip_address text,
  user_agent text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_repair_bookings_store_status on public.repair_bookings (store_slug, status);
create index if not exists idx_repair_bookings_created_at on public.repair_bookings (created_at desc);

