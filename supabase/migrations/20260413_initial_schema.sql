drop policy if exists "public can read active stores" on public.stores;
create policy "public can read active stores"
on public.stores
for select
to anon, authenticated
using (is_active = true);

drop policy if exists "public can read categories" on public.categories;
create policy "public can read categories"
on public.categories
for select
to anon, authenticated
using (true);

drop policy if exists "public can read visible products" on public.products;
create policy "public can read visible products"
on public.products
for select
to anon, authenticated
using (is_visible = true);

drop policy if exists "public can read product images" on public.product_images;
create policy "public can read product images"
on public.product_images
for select
to anon, authenticated
using (
  exists (
    select 1
    from public.products
    where products.id = product_images.product_id
      and products.is_visible = true
  )
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

drop trigger if exists set_updated_at_stores on public.stores;
create trigger set_updated_at_stores
before update on public.stores
for each row execute function public.set_updated_at();

drop trigger if exists set_updated_at_categories on public.categories;
create trigger set_updated_at_categories
before update on public.categories
for each row execute function public.set_updated_at();

drop trigger if exists set_updated_at_suppliers on public.suppliers;
create trigger set_updated_at_suppliers
before update on public.suppliers
for each row execute function public.set_updated_at();

drop trigger if exists set_updated_at_products on public.products;
create trigger set_updated_at_products
before update on public.products
for each row execute function public.set_updated_at();

drop trigger if exists set_updated_at_repair_bookings on public.repair_bookings;
create trigger set_updated_at_repair_bookings
before update on public.repair_bookings
for each row execute function public.set_updated_at();

